/* custom.h — новые враги: процедуры поведения, которых нет в ROM.
 *
 * Новый враг занимает свободный тип (10, 13, 74, 75, 119, 120, 121 — в игре не используются).
 * Мод ставит в таблицу поведения (банк 6, $80DE/$815D) адрес из свободной области банка 6
 * ($BFD1-$BFFE), а ядро вешает на этот адрес свою процедуру на C. Там же мод кладёт запасной
 * код 6502 «освободить ячейку» — если ядро без этой процедуры, враг просто исчезнет.
 *
 * Процедура вызывается как обычное поведение: X = ячейка объекта, в стеке — адрес возврата
 * в цикл объектов. Она может вызывать процедуры игры (custom_call) и выходит как RTS.
 */
#ifndef TGL_CUSTOM_H
#define TGL_CUSTOM_H
#include "nes.h"

/* подключить новые процедуры к приставке (вызывает ядро при загрузке ROM) */
void custom_install(Nes *n);

typedef struct CustomInfo {
    int bank;
    uint16_t addr;           /* куда мод направляет тип (таблица поведения хранит addr-1) */
    nes_hook_fn fn;
    const char *name;
    const char *desc;
} CustomInfo;
extern const CustomInfo custom_table[];
extern const int custom_count;

/* Память модов: данные, которым нет места в ROM (своё «псевдо-ПЗУ», 16 КБ). Мод пишет туда
 * строками «64 <адрес 0000-3FFF> <байты…>» — тем же tgl_patch_rom, что и правки ROM.
 * Не входит в сохранение (это часть «ROM с модами» и входит в его контрольную сумму).
 *
 * Свои узоры комнат лабиринта (без ограничений формата игры):
 *   $0000 + 24·Y + X — номер узора комнаты (1-80), 0 — у комнаты узор игры;
 *   $0400 + 144·(номер−1) — 16×9 клеток (ряды 2-10 комнаты), 0 — оставить клетку шаблона,
 *                           иначе значение клетки (как в узорах игры: $09, $01, $05…).
 * Узор игры у такой комнаты не ставится. Особые комнаты не затрагиваются.
 *
 * Свои комнаты (запись комнаты в формате игры, см. tools/labyrinth.py):
 *   $3000 + 24·Y + X — номер своей записи (1-128), 0 — запись игры;
 *   $3800 + 16·(номер−1) — сама запись. Эти 2 КБ видны процессору по адресам $6000-$67FF
 *   (на картридже игры там ничего нет, игра туда не обращается), и указатели на записи
 *   комнат ($E0-$E9, заполняются $8071 банка 5) ядро направляет туда в конце $8071 ($80F4).
 * Узоры поэтому — только до $3000: не больше 78. */
#define MOD_BANK      64
#define MOD_MEM_SIZE  0x4000
#define MOD_PAT_SLOTS 78
#define MOD_ROOM_IDX  0x3000
#define MOD_WIN_BASE  0x3800     /* окно $6000-$67FF */
#define MOD_WIN_SIZE  0x0800
extern uint8_t custom_mod_mem[MOD_MEM_SIZE];
void custom_mod_clear(void);
int custom_mod_write(int addr, const uint8_t *data, int len);

/* Читы (вызывать в конце каждого кадра): бит 0 — бессмертие (жизнь = максимум), бит 1 — враг
 * гибнет с первого попадания снаряда игрока (перехват $D31C в custom.c), бит 2 — все
 * спецоружия уровня 3 и чипы всегда на пределе (оружие после выключения остаётся). */
void custom_cheats(Nes *n, int flags);

/* ---- Арт мода: свои картинки объектов (любого размера) вместо их спрайтов NES ----
 * Картинка привязана к (тип объекта, номер кадра спрайта $0548): в каждом копировании
 * спрайтов ($4014) ядро запоминает объекты (тип, кадр, X, Y) и убирает из спрайтов приставки
 * те, что лежат на месте спрайтов этого кадра (смещения dx,dy от X/Y объекта, как в буфере
 * $0200; ячейку 0 не трогает — по ней игра делит экран). Картинку рисует tgl_get_frame_rgba
 * поверх кадра в точке X+ax, Y+ay+1. На игру не влияет: правится только копия спрайтов в
 * видеочипе, память игры та же. */
#define ART_MAX      256
#define ART_POOL     (512 * 1024)
#define ART_HIDE_MAX 32
int  custom_art_add(int type, int frame, int ax, int ay, int w, int h, const uint8_t *rgba, const int8_t *hide, int nhide);
void custom_art_clear(void);
extern int custom_art_count;
void custom_art_dma(Nes *n);                  /* из копирования спрайтов */
void custom_art_draw(uint8_t *rgba);          /* 256×240 RGBA */

#endif
