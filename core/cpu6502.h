/* cpu6502.h — процессор NES (Ricoh 2A03, ядро MOS 6502 без десятичного режима).
 *
 * Потактовая модель: каждый такт процессора — ровно одно обращение к шине
 * (включая «пустые» чтения, как у настоящего 6502). Шина (nes.c) на каждом
 * обращении продвигает видеочип и звук на один такт, поэтому прерывания,
 * подкачка DMC и чтение регистров происходят в те же такты, что и в оригинале.
 *
 * Эмулятор нужен порту как «подложка»: пока процедура игры не переведена на C,
 * её исполняет этот процессор. Переведённые процедуры подменяют оригинальные
 * по адресу (см. hooks в nes.h).
 */
#ifndef CPU6502_H
#define CPU6502_H

#include <stdint.h>

typedef uint8_t  (*cpu_read_fn)(void *ctx, uint16_t addr);
typedef void     (*cpu_write_fn)(void *ctx, uint16_t addr, uint8_t value);

enum {
    FLAG_C = 0x01, FLAG_Z = 0x02, FLAG_I = 0x04, FLAG_D = 0x08,
    FLAG_B = 0x10, FLAG_U = 0x20, FLAG_V = 0x40, FLAG_N = 0x80
};

typedef struct Cpu {
    uint8_t  a, x, y, s, p;
    uint16_t pc;
    uint64_t cycles;          /* всего тактов (увеличивает шина на каждом обращении) */
    int      jammed;          /* процессор встал на недопустимой инструкции */

    /* линии прерываний: их выставляет «приставка» */
    int      nmi_level;       /* выход NMI видеочипа (vblank && разрешено) */
    int      irq_line;        /* уровень IRQ (DMC) */

    /* опрос прерываний, как в настоящем 6502 (и в Mesen): состояние на конец
     * каждого такта, решение — по состоянию на предпоследнем такте инструкции */
    int      need_nmi, prev_need_nmi, prev_nmi_level;
    int      run_irq, prev_run_irq;

    cpu_read_fn  read;        /* одно обращение = один такт */
    cpu_write_fn write;
    void    *ctx;
} Cpu;

void cpu_init(Cpu *c, cpu_read_fn rd, cpu_write_fn wr, void *ctx);
/* Сброс: 7 тактов, как у оригинала (без записи в стек). */
void cpu_reset(Cpu *c);
/* Выполняет одну инструкцию и, если пора, вход в прерывание. */
void cpu_step(Cpu *c);
/* Конец такта: опрос линий прерываний. Шина вызывает сама после каждого
 * обращения; отдельно — после тактов подкачки DMA, где процессор стоит. */
void cpu_end_cycle(Cpu *c);
/* Вход в прерывание (7 тактов): NMI, если он ждёт, иначе IRQ. Нужен переведённому коду,
 * чтобы принять прерывание на той же границе инструкции, что и оригинал. */
void cpu_interrupt(Cpu *c);

/* Вспомогательные функции для переведённого кода: стек как у процессора. */
void    cpu_push(Cpu *c, uint8_t v);
uint8_t cpu_pull(Cpu *c);

#endif
